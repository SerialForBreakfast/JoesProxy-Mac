import Foundation

/// Type of media payload in a streaming session.
enum StreamingSegmentMediaType: String, Codable, Equatable, Sendable {
    case video
    case audio
    case subtitle
    case initSegment
    case manifest
    case unknown
}

/// A bitrate tier / variant from the master manifest ladder.
struct StreamingBitrateVariant: Identifiable, Codable, Equatable, Sendable {
    var id: String { "\(bandwidth)_\(resolution ?? "unknown")" }
    let bandwidth: Int
    let averageBandwidth: Int?
    let resolution: String?
    let codecs: String?
    let frameRate: Double?
    let name: String?

    var displayTitle: String {
        if let resolution {
            return "\(resolution) (\(formattedBandwidth))"
        }
        return formattedBandwidth
    }

    var formattedBandwidth: String {
        if bandwidth >= 1_000_000 {
            return String(format: "%.1f Mbps", Double(bandwidth) / 1_000_000.0)
        } else {
            return "\(bandwidth / 1000) kbps"
        }
    }
}

/// A downloaded media segment analyzed for streaming performance.
struct StreamingWaterfallSegment: Identifiable, Codable, Equatable, Sendable {
    var id: SessionRecord.ID { sessionID }
    let sessionID: SessionRecord.ID
    let uri: String
    let sequenceNumber: Int?
    let mediaType: StreamingSegmentMediaType
    let variantBandwidth: Int?
    let variantResolution: String?
    let segmentDuration: TimeInterval
    let downloadDuration: TimeInterval
    let byteCount: Int
    let downloadSpeedBps: Double
    let startedAt: Date
    let completedAt: Date
    let ttfb: TimeInterval?
    let isSlowDownload: Bool
    let isCacheHit: Bool?

    var formattedSpeed: String {
        if downloadSpeedBps >= 1_000_000 {
            return String(format: "%.1f Mbps", downloadSpeedBps / 1_000_000.0)
        } else {
            return String(format: "%.0f kbps", downloadSpeedBps / 1000.0)
        }
    }
}

/// Category of adaptive bitrate switch.
enum StreamingSwitchType: String, Codable, Equatable, Sendable {
    case stepUp
    case stepDown
    case emergencyDrop
    case oscillation
}

/// Represents a detected bitrate quality switch event.
struct StreamingQualitySwitchEvent: Identifiable, Codable, Equatable, Sendable {
    var id: String { "\(timestamp.timeIntervalSince1970)_\(triggerSessionID.uuidString)" }
    let timestamp: Date
    let fromBandwidth: Int?
    let toBandwidth: Int?
    let fromResolution: String?
    let toResolution: String?
    let switchType: StreamingSwitchType
    let triggerSessionID: SessionRecord.ID
}

/// A single point on the projected player buffer health curve.
struct StreamingBufferPoint: Identifiable, Codable, Equatable, Sendable {
    var id: TimeInterval { timestamp.timeIntervalSince1970 }
    let timestamp: Date
    let estimatedBufferSeconds: Double
    let isStallRisk: Bool
}

/// Complete diagnostic report generated by the Streaming Waterfall Engine.
struct StreamingQualityWaterfallReport: Codable, Equatable, Sendable {
    let manifestSessionID: SessionRecord.ID?
    let manifestKind: String
    let bitrateLadder: [StreamingBitrateVariant]
    let segments: [StreamingWaterfallSegment]
    let switchingEvents: [StreamingQualitySwitchEvent]
    let bufferProjection: [StreamingBufferPoint]
    let ttff: TimeInterval?
    let totalPlayableDuration: TimeInterval
    let averageBitrateBps: Double
    let slowSegmentCount: Int
    let oscillationCount: Int
    let estimatedStallCount: Int
    let cdnCacheHitRatio: Double?

    static var empty: StreamingQualityWaterfallReport {
        StreamingQualityWaterfallReport(
            manifestSessionID: nil,
            manifestKind: "None",
            bitrateLadder: [],
            segments: [],
            switchingEvents: [],
            bufferProjection: [],
            ttff: nil,
            totalPlayableDuration: 0,
            averageBitrateBps: 0,
            slowSegmentCount: 0,
            oscillationCount: 0,
            estimatedStallCount: 0,
            cdnCacheHitRatio: nil
        )
    }
}
